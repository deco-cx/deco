/** Fresh's request handler, as returned by `createHandler`. */
export type FreshHandler = (
  req: Request,
  info: {
    remoteAddr: { hostname: string; port: number; transport: "tcp" };
    completed: Promise<void>;
  },
) => Promise<Response>;

export interface WorkerOptions {
  /** Virtual file system for the Deno shim (generated by the build). */
  files: Record<string, string>;
  /**
   * Evaluates the site bundle and returns its Fresh handler. Called once, on
   * the first request, after the Deno shim is installed.
   */
  boot: () => Promise<FreshHandler>;
  /**
   * Files served by Workers Static Assets that Fresh may also read, generated
   * by the build: absolute path in the shim's file system (static files under
   * `<root>/static`, island bundles under `<root>/_fresh`) to `[URL path in
   * Static Assets, size]`. Their content is fetched through the `ASSETS`
   * binding, so a path routed to the Worker first (`assets.run_worker_first`
   * in wrangler.jsonc) goes through the site's `_middleware` and is then
   * served by Fresh, as on Deno.
   */
  lazyFiles?: Record<string, [string, number]>;
  /**
   * The page cache (`pageCache.ts`): on by default, as the CDN caches the
   * site's pages on Deno. `false` turns it off; so does the env var
   * `DECO_WORKER_PAGE_CACHE=false`. `keyCookies` / `bypassCookies` default to
   * the env vars `DECO_PAGE_CACHE_KEY_COOKIES` /
   * `DECO_PAGE_CACHE_BYPASS_COOKIES` (comma-separated cookie name prefixes).
   */
  pageCache?: false | { keyCookies?: string[]; bypassCookies?: string[] };
}

/** A Cloudflare Worker module (`export default`). */
export interface Worker {
  fetch(
    req: Request,
    env: Record<string, unknown>,
    ctx: ExecutionContextLike,
  ): Promise<Response>;
}

/** The first value that is a non-empty string (env bindings can be empty or
 *  not text at all). */
const firstNonEmpty = (...values: unknown[]): string | undefined =>
  values.find((v): v is string => typeof v === "string" && v.trim() !== "");

/** Where `scripts/workerd.ts` embeds the Fresh snapshot (islands' build id). */
export const SNAPSHOT_FILE = "/app/_fresh/snapshot.json";

/** The Fresh build id of the islands bundled in this Worker, if any. */
export function snapshotBuildId(
  files: Record<string, string>,
): string | undefined {
  try {
    return firstNonEmpty(JSON.parse(files[SNAPSHOT_FILE] ?? "{}")?.build_id);
  } catch {
    return undefined;
  }
}

/**
 * The page cache version: the deploy id (the commit, from the builder) plus the
 * Fresh build id of the islands bundled in this Worker. A rebuild of the same
 * commit gets new `/_frsh/js/<build_id>/` URLs, so cached pages from the
 * previous build would point at islands that no longer exist (404, dead UI).
 * Without a deploy id the version is empty, which keeps the page cache off.
 */
export function pageCacheVersion(
  env: Record<string, unknown>,
  buildId?: string,
): string {
  const deployId = firstNonEmpty(env.BUILD_HASH, env.DENO_DEPLOYMENT_ID);
  if (!deployId) return "";
  return buildId ? `${deployId}:${buildId}` : deployId;
}

/** Where `scripts/workerd.ts` embeds the precomputed editor schemas. */
export const SCHEMAS_FILE = "/app/.deco/schemas.gen.json";

/**
 * The Cloudflare Worker for a Fresh + deco site:
 *
 * - installs the Deno shim before the site code is evaluated;
 * - boots the site on the first request (workerd forbids timers, random
 *   values and I/O while modules are evaluated, so the bundle body has to
 *   run inside a request);
 * - makes loader cache writes part of the request's `waitUntil`;
 * - handles Content-Encoding as Deno does (`encoding.ts`);
 * - caches the pages deco marks public (`pageCache.ts`), as the CDN does on
 *   Deno: a Worker route runs before Cloudflare's own cache.
 */
interface AssetsBinding {
  fetch(req: Request): Promise<Response>;
}

/**
 * The app boot, shared by the isolate's requests.
 *
 * The boot runs inside the request that starts it (workerd forbids I/O outside
 * a request). If that request is cancelled before the boot settles (its client
 * disconnected), workerd fails every other request waiting on it with "This
 * promise was created by a request that has since ended". So the request that
 * starts the boot keeps itself alive until the boot settles (`waitUntil`), and
 * a request whose wait fails on a boot another request started boots again,
 * once, in its own context. A failed boot is never cached.
 */
export function sharedBoot<T>(): (
  ctx: ExecutionContextLike,
  start: () => Promise<T>,
) => Promise<T> {
  let current: Promise<T> | undefined;
  return async (ctx, start) => {
    for (let attempt = 0;; attempt++) {
      let startedHere = false;
      if (!current) {
        current = start();
        startedHere = true;
        ctx.waitUntil(current.catch(() => {}));
      }
      const booting = current;
      try {
        return await booting;
      } catch (err) {
        if (current === booting) current = undefined;
        if (startedHere || attempt > 0) throw err;
      }
    }
  };
}

export function createWorker(
  { files, boot, lazyFiles, pageCache }: WorkerOptions,
): Worker {
  const app = sharedBoot<FreshHandler>();
  const buildId = snapshotBuildId(files);
  return {
    async fetch(
      req: Request,
      env: Record<string, unknown>,
      ctx: ExecutionContextLike,
    ): Promise<Response> {
      const start = () =>
        runWithExecutionContext(ctx, () => {
          installDenoShim({
            env: {
              ...env,
              // A Worker is always a deploy: without a deployment id deco runs in
              // dev mode (section errors rendered to visitors, a missing site
              // name tolerated). The control-plane builder passes the commit as
              // BUILD_HASH; fall back to a fixed id for hand-made deploys.
              DENO_DEPLOYMENT_ID: firstNonEmpty(
                env.DENO_DEPLOYMENT_ID,
                env.BUILD_HASH,
              ) ?? "workerd",
              // /deco/meta reads the build-time schemas (no TS parsing on workerd).
              ...(SCHEMAS_FILE in files
                ? { DECO_SCHEMAS_FILE: SCHEMAS_FILE }
                : {}),
            },
            files,
            ...fromAssets(lazyFiles, env.ASSETS),
          });
          keepCacheWritesAlive();
          installDenoFetch();
          return boot();
        });
      const handler = await app(ctx, start);
      const render = () =>
        runWithExecutionContext(ctx, () =>
          handler(req, {
            remoteAddr: {
              hostname: req.headers.get("cf-connecting-ip") ?? "127.0.0.1",
              port: 0,
              transport: "tcp",
            },
            completed: Promise.resolve(),
          }));
      if (pageCache === false || env.DECO_WORKER_PAGE_CACHE === "false") {
        return sendAsIs(await render());
      }
      return sendAsIs(
        await servePage(req, ctx, render, {
          version: pageCacheVersion(env, buildId),
          keyCookies: pageCache?.keyCookies ??
            listFromEnv(env.DECO_PAGE_CACHE_KEY_COOKIES),
          bypassCookies: pageCache?.bypassCookies ??
            listFromEnv(env.DECO_PAGE_CACHE_BYPASS_COOKIES),
        }),
      );
    },
  };
}

interface FreshPlugin {
  name: string;
  islands?: { baseLocation: string; paths: string[] };
}

/**
 * Adapts a Fresh manifest and config to run from a bundle on workerd:
 *
 * - Fresh loads plugin islands with `import(join(baseLocation, path))`. A
 *   bundle has no files to import, so they are registered in the manifest
 *   instead (under the name the Fresh snapshot uses) from `pluginIslands`,
 *   keyed by file name.
 * - Paths point at the shim's file system (`/app`).
 */
export function freshForWorkerd<
  M extends { islands: Record<string, unknown>; baseUrl: string },
  C extends { plugins?: FreshPlugin[]; build?: Record<string, unknown> },
>(
  manifest: M,
  config: C,
  { pluginIslands = {}, root = "/app" }: {
    pluginIslands?: Record<string, unknown>;
    root?: string;
  } = {},
): { manifest: M; config: C } {
  const islands = { ...manifest.islands };
  const plugins = config.plugins?.map((plugin) => {
    if (!plugin.islands) return plugin;
    for (const path of plugin.islands.paths) {
      const file = path.split("/").pop()!;
      const module = pluginIslands[file];
      if (!module) {
        throw new Error(
          `plugin ${plugin.name}: island ${path} is not in the worker bundle`,
        );
      }
      islands[`./islands/${file}`] = module;
    }
    return { ...plugin, islands: undefined };
  });
  return {
    manifest: { ...manifest, islands, baseUrl: `file://${root}/fresh.gen.ts` },
    config: {
      ...config,
      plugins,
      staticDir: `${root}/static`,
      build: { ...config.build, outDir: `${root}/_fresh` },
    } as any,
  };
}

/** Lazy files for the shim: sizes up front, content from `ASSETS`. */
const fromAssets = (
  index: Record<string, [string, number]> | undefined,
  assets: unknown,
) => {
  const binding = assets as AssetsBinding | undefined;
  if (!index || typeof binding?.fetch !== "function") return {};
  const lazyFiles: Record<string, number> = {};
  for (const [path, [, size]] of Object.entries(index)) {
    lazyFiles[path] = size;
  }
  return {
    lazyFiles,
    loadLazyFile: async (path: string) => {
      const urlPath = index[path]?.[0];
      if (!urlPath) throw new Error(`not an asset: ${path}`);
      // Encode each segment: file names may contain `?`, `#`, `%`...
      const encoded = urlPath.split("/").map(encodeURIComponent).join("/");
      // The host is ignored by the ASSETS binding. Its HTML handling answers
      // `/page.html` with a redirect to `/page`: follow a few, in the binding.
      let url = new URL(encoded, "https://assets.invalid");
      let res = await binding.fetch(new Request(url));
      for (
        let hop = 0;
        hop < 3 && res.status >= 300 && res.status < 400;
        hop++
      ) {
        const location = res.headers.get("location");
        if (!location) break;
        url = new URL(location, url);
        res = await binding.fetch(new Request(url));
      }
      if (!res.ok) {
        throw new Error(`asset ${urlPath}: ASSETS ${res.status}`);
      }
      return new Uint8Array(await res.arrayBuffer());
    },
  };
};
